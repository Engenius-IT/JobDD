/**
 * 🚀 ฟังก์ชันจัดเรียงสัญชาติ: ล็อค "ไทย" ขึ้นอันดับ 1 เสมอ 
 * ส่วนที่เหลือเรียงลำดับตามพจนานุกรม ก-ฮ หรือ A-Z ตามภาษาหลักของระบบ (locale)
 */
export const getSortedNationalities = (locale: 'th' | 'en' = 'th') => {
  return Object.entries(NATIONALITIES_DATA)
    .map(([key, value]) => ({
      key,
      label: value[locale] || value['th']
    }))
    .sort((a, b) => {
      if (a.key === 'thai') return -1;
      if (b.key === 'thai') return 1;
      return a.label.localeCompare(b.label, locale);
    });
};